import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ResearchProgressDelivery } from "../../src/runtime/forum/research-progress-delivery.js";
import { WorkflowSwitchRerunService } from "../../src/runtime/thread/workflow-switch-rerun-service.js";
import { DiscordReplySender } from "../../src/runtime/message/discord-reply-sender.js";
import { SqliteStore } from "../../src/storage/sqlite-store.js";
import type { QueuedMessage } from "../../src/runtime/types.js";
import { FakeDiscordWorld } from "../support/fake-discord-sink.js";

test("progress batches at 30 seconds and workflow replacement cancels queued notices and old result chunks", async t => {
  const directory = mkdtempSync(join(tmpdir(), "progress-delivery-"));
  const store = new SqliteStore(join(directory, "test.sqlite"), process.cwd());
  store.migrate();
  t.after(() => { store.close(); rmSync(directory, { recursive: true, force: true }); });
  t.mock.timers.enable({ apis: ["setTimeout", "Date"], now: 100_000 });
  const world = new FakeDiscordWorld();
  const root = world.createTextChannel({ id: "root" });
  const thread = world.createThread({ id: "thread", parent: root });
  const item = { envelope: { channelId: "thread", messageId: "message" }, message: { channel: thread }, source: "live" } as unknown as QueuedMessage;
  const switcher = new WorkflowSwitchRerunService(store, { warn: () => {}, debug: () => {} });
  store.messageProcessing.tryAcquire("message", "thread");
  const queued: QueuedMessage[] = [];
  switcher.setEnqueueRerun(next => { queued.push(next); return true; });
  const release = switcher.trackActive(item);
  const signal = switcher.activeSignal(item)!;
  const sender = new DiscordReplySender();
  const sentAt: number[] = [];
  const delivery = new ResearchProgressDelivery(async content => { sentAt.push(Date.now()); await sender.sendChunksToChannel(thread as never, content, signal); }, error => { throw error; }, signal);
  await delivery.offer("条件Aを確認。条件Bを調べています。");
  await delivery.offer("条件Bを確認。未確認点Cを調べています。");
  await delivery.offer("適用限界Dも確認しています。");
  t.mock.timers.tick(29_999);
  assert.equal(world.sink.sentTexts().length, 1);
  t.mock.timers.tick(1);
  await new Promise<void>(resolve => setImmediate(resolve));
  assert.equal(world.sink.sentTexts().length, 2);
  assert.match(world.sink.sentTexts()[1]!, /条件B[\s\S]*適用限界D/);
  assert.deepEqual(sentAt, [100_000, 130_000]);
  t.mock.timers.tick(90_000);
  assert.equal(world.sink.sentTexts().length, 2, "no new event means no repeated status");
  await delivery.offer("追加の原文を確認しています。");
  await delivery.offer("この通知は切替時に破棄されます。");
  const beforeSwitch = world.sink.sentTexts().length;
  assert.equal(switcher.requestRerun("thread").enqueued, true);
  assert.equal(signal.aborted, true);
  t.mock.timers.tick(60_000);
  await delivery.offer("旧実行の遅れた通知");
  await assert.rejects(sender.sendChunksToChannel(thread as never, "旧実行の最終回答", signal));
  assert.equal(world.sink.sentTexts().length, beforeSwitch);
  const releaseNew = switcher.trackActive(queued[0]!);
  release();
  assert.equal(switcher.activeSignal(queued[0]!)!.aborted, false, "old cleanup must not abort the replacement");
  assert.equal(switcher.activeSignal(item)!.aborted, true);

  // Cancellation between Discord chunks stops the remaining chunks as well.
  const nextController = new AbortController();
  const originalSend = thread.send.bind(thread);
  thread.send = async input => { const result = await originalSend(input); nextController.abort(); return result; };
  await assert.rejects(sender.sendChunksToChannel(thread as never, "長文の結果。".repeat(700), nextController.signal));
  assert.equal(world.sink.sentTexts().length, beforeSwitch + 1);
  assert.ok(world.sink.events.every(event => event.channelId === "thread"));
  releaseNew();
});
